# ============================================================
# 3. ПОЛУЧИТЬ СЛУЧАЙНЫЙ СМАЙЛ
# ============================================================

def random_emoji(category: str = "happy") -> str:
    """
    Возвращает случайный смайл из выбранной категории.
    """

    emojis = EMOJIS.get(category)

    if not emojis:
        emojis = EMOJIS["happy"]

    return random.choice(emojis)


# ============================================================
# 4. ПОЛУЧИТЬ ФРАЗУ-РЕАКЦИЮ
# ============================================================

def reaction(category: str) -> str:
    """
    Возвращает фирменную реакцию NEXORA.
    """

    return NEXORA_REACTIONS.get(
        category,
        random_emoji("happy"),
    )


# ============================================================
# 5. ДОБАВИТЬ СМАЙЛ К ТЕКСТУ
# ============================================================

def add_emoji(text: str, category: str = "happy") -> str:
    """
    Добавляет подходящий случайный смайл в начало текста.
    """

    if not text:
        return text

    emoji = random_emoji(category)

    return f"{emoji} {text}"


